import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:go_router/go_router.dart';
import 'package:google_fonts/google_fonts.dart';
import '../../../../core/router/route_names.dart';
import '../../../trips/presentation/bloc/trip_bloc.dart';
import '../../../trips/presentation/bloc/trip_state.dart';
import '../../../trips/domain/entities/trip_entity.dart';
import '../../domain/entities/itinerary_entity.dart';
import '../bloc/itinerary_bloc.dart';
import '../bloc/itinerary_event.dart';
import '../bloc/itinerary_state.dart';

/// "Plans / Alternatives" screen connected directly to ItineraryBloc & AI engine.
/// Presents dynamic Plan A, B, and C generated by the backend AI microservice,
/// with budget stats, duration, activity counts, highlights, and selection capabilities.
class PlansAlternativesPage extends StatefulWidget {
  final String tripId;

  const PlansAlternativesPage({
    super.key,
    required this.tripId,
  });

  @override
  State<PlansAlternativesPage> createState() => _PlansAlternativesPageState();
}

class _PlansAlternativesPageState extends State<PlansAlternativesPage> {
  String? _selectedPlanId;

  final List<String> _planImages = const [
    'assets/images/sunset_beach_plan.jpg',
    'assets/images/coastal_cliffs_plan.jpg',
    'assets/images/palolem_beach.jpg',
    'assets/images/trip_goa.jpg',
  ];

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        context.read<ItineraryBloc>().add(ItinerariesFetchRequested(widget.tripId));
      }
    });
  }

  void _generateWithAi(TripEntity? trip) {
    final destination = trip?.name.split(' ').first ?? 'Goa';
    final sDate = trip?.tripStartDate != null
        ? '${trip!.tripStartDate!.year}-${trip.tripStartDate!.month.toString().padLeft(2, '0')}-${trip.tripStartDate!.day.toString().padLeft(2, '0')}'
        : '2026-11-10';
    final eDate = trip?.tripEndDate != null
        ? '${trip!.tripEndDate!.year}-${trip.tripEndDate!.month.toString().padLeft(2, '0')}-${trip.tripEndDate!.day.toString().padLeft(2, '0')}'
        : '2026-11-15';

    context.read<ItineraryBloc>().add(
          ItineraryGenerateRequested(
            tripId: widget.tripId,
            origin: 'Mumbai',
            destination: destination,
            startDate: sDate,
            endDate: eDate,
            memberCount: trip?.members.isNotEmpty == true ? trip!.members.length : 4,
          ),
        );
  }

  void _handleSelectPlan(String itineraryId) {
    context.read<ItineraryBloc>().add(
          ItinerarySelectRequested(
            tripId: widget.tripId,
            itineraryId: itineraryId,
          ),
        );
    context.push(RouteNames.itineraryPath(widget.tripId));
  }

  @override
  Widget build(BuildContext context) {
    final topPadding = MediaQuery.of(context).padding.top;
    final bottomPadding = MediaQuery.of(context).padding.bottom;

    final tripState = context.watch<TripBloc>().state;
    TripEntity? trip;
    if (tripState is TripDetailLoadedState) {
      trip = tripState.trip;
    }

    return Scaffold(
      backgroundColor: const Color(0xFFFAF9F6),
      body: BlocConsumer<ItineraryBloc, ItineraryState>(
        listener: (context, state) {
          if (state is ItinerariesLoadedState) {
            if (state.successMessage != null) {
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(
                  content: Text(state.successMessage!),
                  backgroundColor: const Color(0xFF004E64),
                  behavior: SnackBarBehavior.floating,
                ),
              );
            }
            if (_selectedPlanId == null && state.selectedItinerary != null) {
              setState(() {
                _selectedPlanId = state.selectedItinerary!.id;
              });
            }
          } else if (state is ItineraryErrorState) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(
                content: Text(state.message),
                backgroundColor: const Color(0xFFDC2626),
                behavior: SnackBarBehavior.floating,
              ),
            );
          }
        },
        builder: (context, state) {
          if (state is ItineraryLoadingState) {
            return Center(
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  const CircularProgressIndicator(color: Color(0xFF004E64)),
                  const SizedBox(height: 20),
                  Text(
                    'AI is crafting your group itineraries...',
                    style: GoogleFonts.inter(
                      fontSize: 15,
                      fontWeight: FontWeight.w600,
                      color: const Color(0xFF004E64),
                    ),
                  ),
                  const SizedBox(height: 6),
                  Text(
                    'Analyzing collective preferences & optimal routes',
                    style: GoogleFonts.inter(
                      fontSize: 12.5,
                      color: const Color(0xFF64748B),
                    ),
                  ),
                ],
              ),
            );
          }

          List<ItineraryEntity> itineraries = [];
          if (state is ItinerariesLoadedState) {
            itineraries = state.itineraries;
          }

          return Stack(
            children: [
              SingleChildScrollView(
                physics: const BouncingScrollPhysics(),
                padding: EdgeInsets.only(
                  top: topPadding + 68,
                  bottom: bottomPadding + 90,
                  left: 18,
                  right: 18,
                ),
                child: Column(
                  children: [
                    const SizedBox(height: 8),

                    // Empty state banner if no plans exist yet
                    if (itineraries.isEmpty)
                      Container(
                        padding: const EdgeInsets.all(24),
                        decoration: BoxDecoration(
                          color: Colors.white,
                          borderRadius: BorderRadius.circular(24),
                          border: Border.all(color: const Color(0xFFE2E8F0)),
                        ),
                        child: Column(
                          children: [
                            Container(
                              width: 64,
                              height: 64,
                              decoration: const BoxDecoration(
                                color: Color(0xFFDEF2F1),
                                shape: BoxShape.circle,
                              ),
                              child: const Icon(
                                Icons.auto_awesome,
                                size: 32,
                                color: Color(0xFF004E64),
                              ),
                            ),
                            const SizedBox(height: 16),
                            Text(
                              'Generate AI Itinerary Plans',
                              style: GoogleFonts.inter(
                                fontSize: 18,
                                fontWeight: FontWeight.w800,
                                color: const Color(0xFF004E64),
                              ),
                            ),
                            const SizedBox(height: 8),
                            Text(
                              'We will combine all group preferences and craft optimal day-by-day alternatives for your trip.',
                              textAlign: TextAlign.center,
                              style: GoogleFonts.inter(
                                fontSize: 13,
                                color: const Color(0xFF64748B),
                                height: 1.4,
                              ),
                            ),
                            const SizedBox(height: 20),
                            ElevatedButton.icon(
                              onPressed: () => _generateWithAi(trip),
                              icon: const Icon(Icons.bolt_rounded, color: Colors.white),
                              label: Text(
                                'Generate Plans with AI',
                                style: GoogleFonts.inter(
                                  fontSize: 14.5,
                                  fontWeight: FontWeight.w700,
                                  color: Colors.white,
                                ),
                              ),
                              style: ElevatedButton.styleFrom(
                                backgroundColor: const Color(0xFF004E64),
                                padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 14),
                                shape: RoundedRectangleBorder(
                                  borderRadius: BorderRadius.circular(20),
                                ),
                              ),
                            ),
                          ],
                        ),
                      ),

                    // ── Dynamic Itinerary Plan Cards ─────────────────────────
                    ...itineraries.asMap().entries.map((entry) {
                      final index = entry.key;
                      final plan = entry.value;
                      final planCode = 'PLAN ${String.fromCharCode(65 + index)}';
                      final planName = (plan.variantType ?? 'Balanced').toUpperCase();
                      final isSelected = _selectedPlanId == plan.id ||
                          (_selectedPlanId == null && (plan.isSelected || index == 0));
                      final dayCount = plan.items.map((i) => i.dayNumber).toSet().length;
                      final durationText = dayCount > 0 ? '$dayCount Days' : '4 Days';
                      final placesText = '${plan.items.length} Activities';
                      final budgetText = plan.totalCostPerPerson != null
                          ? '₹${plan.totalCostPerPerson!.toStringAsFixed(0)}'
                          : '₹18,500';

                      final highlights = plan.items.take(3).map((i) => i.activityName).toList();
                      if (highlights.isEmpty) {
                        highlights.addAll([
                          'Beaches & scenic sunset views',
                          'Authentic coastal food spots',
                          'Flexible afternoon leisure',
                        ]);
                      }

                      final imagePath = _planImages[index % _planImages.length];

                      return Padding(
                        padding: const EdgeInsets.only(bottom: 20),
                        child: InkWell(
                          onTap: () {
                            setState(() {
                              _selectedPlanId = plan.id;
                            });
                          },
                          borderRadius: BorderRadius.circular(24),
                          child: Container(
                            decoration: BoxDecoration(
                              color: Colors.white,
                              borderRadius: BorderRadius.circular(24),
                              border: Border.all(
                                color: isSelected ? const Color(0xFF007791) : const Color(0xFFE2E8F0),
                                width: isSelected ? 2.0 : 1.0,
                              ),
                              boxShadow: [
                                BoxShadow(
                                  color: const Color(0xFF0F172A).withValues(alpha: 0.04),
                                  blurRadius: 14,
                                  offset: const Offset(0, 3),
                                ),
                              ],
                            ),
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                // Cover Photo Header
                                Stack(
                                  children: [
                                    ClipRRect(
                                      borderRadius: const BorderRadius.vertical(top: Radius.circular(23)),
                                      child: SizedBox(
                                        height: 140,
                                        width: double.infinity,
                                        child: Image.asset(
                                          imagePath,
                                          fit: BoxFit.cover,
                                          errorBuilder: (context, error, stackTrace) => Container(
                                            color: const Color(0xFFDEF2F1),
                                            child: const Center(
                                              child: Icon(Icons.beach_access, color: Color(0xFF004E64)),
                                            ),
                                          ),
                                        ),
                                      ),
                                    ),
                                    if (plan.isSelected || index == 0)
                                      Positioned(
                                        top: 12,
                                        left: 14,
                                        child: Container(
                                          padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                                          decoration: BoxDecoration(
                                            color: const Color(0xFFF59E0B),
                                            borderRadius: BorderRadius.circular(16),
                                          ),
                                          child: Text(
                                            plan.isSelected ? 'Selected Plan' : 'AI Top Pick',
                                            style: GoogleFonts.inter(
                                              fontSize: 11,
                                              fontWeight: FontWeight.w700,
                                              color: const Color(0xFF004E64),
                                            ),
                                          ),
                                        ),
                                      ),
                                  ],
                                ),

                                // Plan Content
                                Padding(
                                  padding: const EdgeInsets.all(18),
                                  child: Column(
                                    crossAxisAlignment: CrossAxisAlignment.start,
                                    children: [
                                      Row(
                                        children: [
                                          Expanded(
                                            child: Text.rich(
                                              TextSpan(
                                                children: [
                                                  TextSpan(
                                                    text: '$planCode — ',
                                                    style: GoogleFonts.inter(
                                                      fontSize: 15,
                                                      fontWeight: FontWeight.w900,
                                                      color: const Color(0xFF004E64),
                                                    ),
                                                  ),
                                                  TextSpan(
                                                    text: planName,
                                                    style: GoogleFonts.inter(
                                                      fontSize: 15,
                                                      fontWeight: FontWeight.w700,
                                                      color: const Color(0xFF004E64),
                                                    ),
                                                  ),
                                                ],
                                              ),
                                            ),
                                          ),
                                          Container(
                                            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 3),
                                            decoration: BoxDecoration(
                                              color: const Color(0xFFDEF2F1),
                                              borderRadius: BorderRadius.circular(12),
                                            ),
                                            child: Text(
                                              'High Match',
                                              style: GoogleFonts.inter(
                                                fontSize: 11,
                                                fontWeight: FontWeight.w700,
                                                color: const Color(0xFF007791),
                                              ),
                                            ),
                                          ),
                                          const SizedBox(width: 8),
                                          Icon(
                                            isSelected
                                                ? Icons.radio_button_checked_rounded
                                                : Icons.radio_button_off_rounded,
                                            color: isSelected
                                                ? const Color(0xFF004E64)
                                                : const Color(0xFFCBD5E1),
                                            size: 22,
                                          ),
                                        ],
                                      ),
                                      const SizedBox(height: 6),
                                      Text(
                                        plan.summary ?? 'Tailored to the group preference consensus.',
                                        style: GoogleFonts.inter(
                                          fontSize: 13,
                                          color: const Color(0xFF64748B),
                                          height: 1.35,
                                        ),
                                      ),
                                      const SizedBox(height: 16),

                                      // Stat Icons Row
                                      Row(
                                        children: [
                                          _buildPlanStat(Icons.account_balance_wallet_outlined, budgetText),
                                          const SizedBox(width: 16),
                                          _buildPlanStat(Icons.calendar_today_outlined, durationText),
                                          const SizedBox(width: 16),
                                          _buildPlanStat(Icons.place_outlined, placesText),
                                        ],
                                      ),
                                      const SizedBox(height: 16),

                                      // Highlights
                                      ...highlights.map(
                                        (hl) => Padding(
                                          padding: const EdgeInsets.only(bottom: 6),
                                          child: Row(
                                            crossAxisAlignment: CrossAxisAlignment.start,
                                            children: [
                                              const Icon(
                                                Icons.check_circle_rounded,
                                                size: 16,
                                                color: Color(0xFF0D9488),
                                              ),
                                              const SizedBox(width: 8),
                                              Expanded(
                                                child: Text(
                                                  hl,
                                                  style: GoogleFonts.inter(
                                                    fontSize: 12.5,
                                                    color: const Color(0xFF334155),
                                                  ),
                                                ),
                                              ),
                                            ],
                                          ),
                                        ),
                                      ),
                                    ],
                                  ),
                                ),
                              ],
                            ),
                          ),
                        ),
                      );
                    }),
                  ],
                ),
              ),

              // ── Sticky Bottom CTA Bar ────────────────────────────────────
              if (itineraries.isNotEmpty)
                Positioned(
                  bottom: 0,
                  left: 0,
                  right: 0,
                  child: Container(
                    padding: EdgeInsets.only(
                      left: 18,
                      right: 18,
                      top: 14,
                      bottom: bottomPadding + 14,
                    ),
                    decoration: BoxDecoration(
                      color: Colors.white,
                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withValues(alpha: 0.08),
                          blurRadius: 16,
                          offset: const Offset(0, -4),
                        ),
                      ],
                    ),
                    child: SizedBox(
                      width: double.infinity,
                      height: 52,
                      child: ElevatedButton(
                        onPressed: () {
                          final selectedId = _selectedPlanId ?? itineraries.first.id;
                          _handleSelectPlan(selectedId);
                        },
                        style: ElevatedButton.styleFrom(
                          backgroundColor: const Color(0xFFF59E0B),
                          elevation: 0,
                          shape: RoundedRectangleBorder(
                            borderRadius: BorderRadius.circular(24),
                          ),
                        ),
                        child: Row(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            Text(
                              'Select Plan & View Itinerary',
                              style: GoogleFonts.inter(
                                fontSize: 15.5,
                                fontWeight: FontWeight.w700,
                                color: const Color(0xFF004E64),
                              ),
                            ),
                            const SizedBox(width: 8),
                            const Icon(
                              Icons.arrow_forward_rounded,
                              size: 18,
                              color: Color(0xFF004E64),
                            ),
                          ],
                        ),
                      ),
                    ),
                  ),
                ),

              // ── Fixed Top Header ─────────────────────────────────────────
              Positioned(
                top: 0,
                left: 0,
                right: 0,
                child: Container(
                  height: topPadding + 58,
                  padding: EdgeInsets.only(
                    top: topPadding + 4,
                    left: 10,
                    right: 18,
                  ),
                  decoration: BoxDecoration(
                    color: Colors.white.withValues(alpha: 0.95),
                    border: const Border(
                      bottom: BorderSide(color: Color(0xFFE2E8F0)),
                    ),
                  ),
                  child: Row(
                    children: [
                      IconButton(
                        icon: const Icon(Icons.arrow_back, color: Color(0xFF004E64), size: 24),
                        onPressed: () => context.pop(),
                      ),
                      const SizedBox(width: 4),
                      Text(
                        'Plans & Alternatives',
                        style: GoogleFonts.inter(
                          fontSize: 18,
                          fontWeight: FontWeight.w800,
                          color: const Color(0xFF004E64),
                        ),
                      ),
                      const Spacer(),
                      IconButton(
                        tooltip: 'Regenerate plans with AI',
                        icon: const Icon(Icons.refresh_rounded, color: Color(0xFF004E64), size: 22),
                        onPressed: () => _generateWithAi(trip),
                      ),
                    ],
                  ),
                ),
              ),
            ],
          );
        },
      ),
    );
  }

  Widget _buildPlanStat(IconData icon, String value) {
    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        Icon(icon, size: 16, color: const Color(0xFF007791)),
        const SizedBox(width: 5),
        Text(
          value,
          style: GoogleFonts.inter(
            fontSize: 12.5,
            fontWeight: FontWeight.w700,
            color: const Color(0xFF004E64),
          ),
        ),
      ],
    );
  }
}
